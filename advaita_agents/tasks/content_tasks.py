        "  preprocessing across queries. If the code rebuilds the index inside "
        "  the per-query loop, do not claim preprocessing benefits. The "
        "  complexity you state must match the code you provide.\n"
        "- COMPLETENESS: Every example explanation must be a complete sentence "
        "  or paragraph ending with proper punctuation. No explanation may be "
        "  truncated mid-sentence. If you are approaching token limits, reduce "
        "  the number of examples rather than leaving explanations incomplete.\n"
